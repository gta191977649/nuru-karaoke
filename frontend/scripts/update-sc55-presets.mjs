import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { SoundBankLoader } from 'spessasynth_core'

const sourceUrl = new URL('../src/soundfont/sc55.sf2', import.meta.url)
const outputUrl = new URL('../src/engine/plugins/gs-over-55/data/sc55Presets.generated.js', import.meta.url)

function stablePreset(preset) {
  return {
    bank: Number(preset.bankMSB) || 0,
    program: Number(preset.program) || 0,
    name: String(preset.name || '').trim(),
  }
}

function render(hash, melodic, drums) {
  return `// Generated by scripts/update-sc55-presets.mjs. Do not edit by hand.\n` +
    `// Source: src/soundfont/sc55.sf2 (SHA-256 ${hash})\n` +
    `export const SC55_SOUNDFONT_SHA256 = '${hash}'\n` +
    `export const SC55_MELODIC_PRESETS = Object.freeze(${JSON.stringify(melodic, null, 2)})\n` +
    `export const SC55_DRUM_PRESETS = Object.freeze(${JSON.stringify(drums, null, 2)})\n`
}

const bytes = await readFile(sourceUrl)
const arrayBuffer = bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength)
const soundBank = SoundBankLoader.fromArrayBuffer(arrayBuffer)
const sortPresets = (a, b) => a.program - b.program || a.bank - b.bank || a.name.localeCompare(b.name)
const melodic = soundBank.presets.filter((preset) => !preset.isGMGSDrum).map(stablePreset).sort(sortPresets)
const drums = soundBank.presets.filter((preset) => preset.isGMGSDrum).map(stablePreset).sort(sortPresets)
const hash = createHash('sha256').update(bytes).digest('hex')
const generated = render(hash, melodic, drums)

if (process.argv.includes('--check')) {
  let current = ''
  try { current = await readFile(outputUrl, 'utf8') } catch { /* missing output */ }
  if (current !== generated) {
    console.error(`SC-55 preset snapshot is stale: ${fileURLToPath(outputUrl)}`)
    process.exitCode = 1
  }
} else {
  await writeFile(outputUrl, generated)
  console.log(`Wrote ${fileURLToPath(outputUrl)} (${melodic.length} melodic, ${drums.length} drum presets)`)
}
